"""Run the whole automated test campaign and write docs/TEST_REPORT.md (STP section 10).

    python tests/report/make_report.py [--perf-json measurements.json]

1. runs pytest three times (API/integration, browser, performance) with JUnit XML output
2. maps every test to the STP test-case IDs in its name (test_tc_upl_03_... -> TC-UPL-03)
3. evaluates the STP section 8 acceptance criteria and writes the report
"""
import argparse
import datetime
import json
import os
import platform
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CASES = json.loads((Path(__file__).parent / "stp_cases.json").read_text(encoding="utf-8"))
OUT = ROOT / "docs" / "TEST_REPORT.md"

# Tests whose names do not carry the TC ID but which verify a case
EXTRA = {
    "test_configured_classifier_is_used_and_named": ["TC-MOD-06", "TC-MET-01"],
    "test_predict_contract_shape": ["TC-MOD-06"],
    "test_unknown_dataset_is_404": ["TC-MOD-06"],
    "test_health_ok_and_not_ready": ["TC-MOD-06"],
    "test_job_reaches_completed_and_result_is_stored": ["TC-JOB-02"],
}
MANUAL = {"TC-SAFE-04": "Manual usability walkthrough with a first-time user; protocol in "
                        "docs/USABILITY_WALKTHROUGH.md (issue #33)"}
LEVELS = [("API, integration and unit", ["-m", "not perf and not ui"]),
          ("Browser (Playwright, Chromium)", ["-m", "ui"]),
          ("Performance", ["-m", "perf"])]


def tc_ids(name):
    ids = []
    for kind, nums in re.findall(r"tc_([a-z]+)_((?:\d\d)(?:_and_\d\d)*)", name):
        for n in re.findall(r"\d\d", nums):
            ids.append(f"TC-{kind.upper()}-{n}")
    base = name.split("[")[0]
    return ids + EXTRA.get(base, [])


def run_level(label, args, tmp):
    xml = Path(tmp) / f"{label.split()[0]}.xml"
    t0 = datetime.datetime.now()
    proc = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", f"--junitxml={xml}"] + args,
                          cwd=ROOT, capture_output=True, text=True)
    seconds = (datetime.datetime.now() - t0).total_seconds()
    tests = []
    for tc in ET.parse(xml).getroot().iter("testcase"):
        outcome = "passed"
        if tc.find("failure") is not None or tc.find("error") is not None:
            outcome = "failed"
        elif tc.find("skipped") is not None:
            outcome = "skipped"
        tests.append({"file": tc.get("classname", "").replace(".", "/") + ".py", "name": tc.get("name"),
                      "outcome": outcome, "time": float(tc.get("time", 0))})
    return {"label": label, "seconds": seconds, "tests": tests, "tail": proc.stdout.strip().splitlines()[-1:]}


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--perf-json", help="output of tests/perf/run_perf.py against the real deployment")
    a = ap.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        levels = [run_level(label, args, tmp) for label, args in LEVELS]

    per_case = {k: [] for k in CASES}
    for lv in levels:
        for t in lv["tests"]:
            for cid in tc_ids(t["name"]):
                if cid in per_case:
                    per_case[cid].append((lv["label"], t))

    def status(cid):
        if cid in MANUAL and not per_case[cid]:
            return "Not executed (manual)"
        tests = [t for _, t in per_case[cid]]
        if not tests:
            return "Not covered"
        if any(t["outcome"] == "failed" for t in tests):
            return "FAIL"
        if all(t["outcome"] == "skipped" for t in tests):
            return "Blocked"
        return "Pass"

    statuses = {cid: status(cid) for cid in CASES}
    n_pass = sum(s == "Pass" for s in statuses.values())
    high = [c for c, v in CASES.items() if v["priority"] == "High"]
    high_pass = sum(statuses[c] == "Pass" for c in high)
    all_tests = [t for lv in levels for t in lv["tests"]]
    failed = [t for t in all_tests if t["outcome"] == "failed"]

    L = []
    w = L.append
    w("# Test execution report (STP-CCFD-1.1, section 10)")
    w("")
    w("This file is generated by `python tests/report/make_report.py`. It is the test execution log and test "
      "summary report (STP section 10, deliverables 2 and 5) for Release 1.0.")
    w("")
    w("## 1. Build and environment")
    w("")
    w("| Item | Value |")
    w("|---|---|")
    w(f"| Build (commit) | `{git('rev-parse', '--short', 'HEAD')}` on branch `{git('rev-parse', '--abbrev-ref', 'HEAD')}` |")
    w(f"| Date | {datetime.datetime.now(datetime.timezone.utc).strftime('%d %b %Y %H:%M')} UTC |")
    w(f"| OS | {platform.system()} {platform.release()} ({platform.machine()}), {os.cpu_count()} CPUs |")
    w(f"| Python | {platform.python_version()} |")
    w("| Also run on | GitHub Actions on every pull request: ubuntu-latest (lint + tests + browser tests) and "
      "windows-latest (tests) |")
    w("")
    w("## 2. Summary")
    w("")
    w("| Level | Tests | Passed | Failed | Skipped | Duration |")
    w("|---|---|---|---|---|---|")
    for lv in levels:
        ts = lv["tests"]
        w(f"| {lv['label']} | {len(ts)} | {sum(t['outcome'] == 'passed' for t in ts)} | "
          f"{sum(t['outcome'] == 'failed' for t in ts)} | {sum(t['outcome'] == 'skipped' for t in ts)} | "
          f"{lv['seconds']:.0f} s |")
    w(f"| **Total** | **{len(all_tests)}** | **{sum(t['outcome'] == 'passed' for t in all_tests)}** | "
      f"**{len(failed)}** | **{sum(t['outcome'] == 'skipped' for t in all_tests)}** | "
      f"**{sum(lv['seconds'] for lv in levels):.0f} s** |")
    w("")
    w(f"**STP test cases:** {n_pass} of {len(CASES)} passed, "
      f"{sum(s.startswith('Not executed') for s in statuses.values())} not executed (manual), "
      f"{sum(s == 'FAIL' for s in statuses.values())} failed, {sum(s == 'Not covered' for s in statuses.values())} "
      "not covered.")
    w("")
    w("### Acceptance criteria (STP section 8)")
    w("")
    pct = 100 * n_pass / len(CASES)
    w("| Criterion | Result | Met |")
    w("|---|---|---|")
    w(f"| All High-priority cases pass | {high_pass} of {len(high)} High cases pass | "
      f"{'Yes' if high_pass == len(high) else 'No'} |")
    w(f"| At least 90 % of the 57 cases pass | {n_pass} of 57 = {pct:.1f} % | {'Yes' if pct >= 90 else 'No'} |")
    w(f"| No High-severity defect open | {'none open' if not failed else str(len(failed)) + ' failing tests'} | "
      f"{'Yes' if not failed else 'No'} |")
    w("")
    rec = ("**Release recommendation: accept Release 1.0.** All acceptance criteria are met. "
           "TC-SAFE-04 (usability walkthrough, Medium) still has to be run by the team with a first-time user "
           "before the final demo.") if (high_pass == len(high) and pct >= 90 and not failed) else \
        "**Release recommendation: do not accept yet** - see the failing cases below."
    w(rec)
    w("")
    w("## 3. Results per STP test case")
    w("")
    w("Effort (Est.) is the STP's estimate for manual execution. Automated, each case takes seconds and runs on "
      "every pull request.")
    w("")
    w("| Case | Title | Priority | Est. | Result | Automated test(s) |")
    w("|---|---|---|---|---|---|")
    for cid, v in CASES.items():
        tests = sorted({f"`{Path(t['file']).name}::{t['name'].split('[')[0]}`" for _, t in per_case[cid]})
        where = "<br>".join(tests) if tests else MANUAL.get(cid, "-")
        w(f"| {cid} | {v['title']} | {v['priority']} | {v['est_min']} min | {statuses[cid]} | {where} |")
    w("")
    w("Substitutions used (allowed by STP section 13, listed in DEVIATIONS T-03): TC-JOB-06 timeout 600 s -> 1 s; "
      "TC-SEC-06 size limit 500 MB -> 100 KB; TC-SEC-09 retention 24 h -> 2 s.")
    w("")
    if a.perf_json:
        perf = json.loads(Path(a.perf_json).read_text())
        w("## 4. Performance measurements on the real deployment")
        w("")
        w("Measured with `tests/perf/run_perf.py` against the system started by `run_all.py` (four processes, "
          "real HTTP), on the machine in section 1.")
        w("")
        w("| Case | Target | Measured | Met |")
        w("|---|---|---|---|")
        for r in perf["TC-PERF-01"]:
            w(f"| TC-PERF-01 {r['file']} | <= 2 s (median of 3) | {r['median_s']} s (status {r['status'][0]}) | "
              f"{'Yes' if r['median_s'] <= 2 else 'No'} |")
        r = perf["TC-PERF-02"]
        w(f"| TC-PERF-02 polling, 10 clients | p95 <= 500 ms, no 5xx | p95 {r['p95_ms']} ms, median {r['median_ms']} ms, "
          f"{r['requests']} requests, {r['errors_5xx']} 5xx | {'Yes' if r['p95_ms'] <= 500 and not r['errors_5xx'] else 'No'} |")
        r = perf["TC-PERF-03"]
        w(f"| TC-PERF-03 {r['file']} | <= 60 s | {r['median_s']} s (status {r['status'][0]}) | "
          f"{'Yes' if r['median_s'] <= 60 else 'No'} |")
        r = perf["TC-PERF-05"]
        w(f"| TC-PERF-05 10 sessions (ML/DL/QML) | uploads <= 2 s, poll p95 <= 500 ms, >= 99 % correct codes | "
          f"max upload {r['upload_max_s']} s, poll p95 {r['poll_p95_ms']} ms, {r['correct_status_pct']} % correct, "
          f"all terminal: {r['all_terminal']} | "
          f"{'Yes' if r['upload_max_s'] <= 2 and r['poll_p95_ms'] <= 500 and r['correct_status_pct'] >= 99 else 'No'} |")
        r = perf["TC-PERF-06"]
        w(f"| TC-PERF-06 {r['file']} | 400 within 5 s of upload completion | {r['median_s']} s client-side incl. "
          f"local transfer (status {r['status'][0]}) | {'Yes' if r['median_s'] <= 5 else 'Upper bound above 5 s - see note'} |")
        w("")
        w("Note on TC-PERF-02: the real ML job on valid_1000.csv finishes in under 2 s, so the 10 pollers read a "
          "completed job, which is the heavier response (it carries all 1,000 predictions). Polling a job that "
          "stays *running* is covered by `test_tc_perf_02_polling_p95_under_500ms`, which uses a deliberately "
          "slow model service.")
        w("")
    w("## 5. Defects found during testing")
    w("")
    w("| # | Found by | Defect | Severity | Status |")
    w("|---|---|---|---|---|")
    w("| DEF-1 | Windows CI job (S2-10) | A rejected upload could not be deleted on Windows because the CSV reader "
      "still held the file open, so the client got 500 instead of 400 (TC-UPL-03/07) | High | Fixed in S2-10 "
      "(reader closed before the error is raised); re-tested on Windows and Ubuntu |")
    w("| DEF-2 | Ragged-row test (S1-09) | A row with extra fields was silently accepted because only the required "
      "columns were parsed | Medium | Fixed in S1-09 (all columns parsed) |")
    w("| DEF-3 | Browser tests (S2-09) | None in the product. The test helper raced with the previous run's "
      "'completed' badge | - | Test fixed |")
    w("")
    if failed:
        w("### Currently failing tests")
        w("")
        for t in failed:
            w(f"- `{t['file']}::{t['name']}`")
        w("")
    w("## 6. Effort")
    w("")
    w(f"The STP estimated {sum(v['est_min'] for v in CASES.values()) / 60:.1f} h of manual execution plus 11 h of "
      f"overhead (31.5 person-hours). The automated campaign runs in about {sum(lv['seconds'] for lv in levels) / 60:.0f} "
      "minutes and repeats on every pull request. The one-off cost moved into writing the tests, which were built "
      "together with each backlog item.")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT}: {n_pass}/57 pass, {len(failed)} failing tests")


if __name__ == "__main__":
    main()
