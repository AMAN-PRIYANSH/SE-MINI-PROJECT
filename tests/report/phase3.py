# ------------------------------------------------------------------ helpers
def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def now():
    return datetime.datetime.now(datetime.timezone.utc)


def header(title, purpose, command):
    return [f"# {title}", "", purpose, "",
            f"Generated by `python tests/report/phase3.py {command}`. Do not edit by hand; run the command again.", "",
            "| Item | Value |", "|---|---|",
            f"| Build (commit on main) | `{git('rev-parse', '--short', 'HEAD')}` |",
            f"| Date and time | {now().strftime('%d %b %Y %H:%M')} UTC |",
            f"| Run by | {git('config', 'user.name') or os.environ.get('USERNAME') or os.environ.get('USER', '-')} |",
            f"| Machine | {platform.system()} {platform.release()} ({platform.machine()}), {os.cpu_count()} CPUs |",
            f"| Python | {platform.python_version()} |", ""]


def tc_ids(name):
    ids = []
    for kind, nums in re.findall(r"tc_([a-z]+)_((?:\d\d)(?:_and_\d\d)*)", name):
        ids += [f"TC-{kind.upper()}-{n}" for n in re.findall(r"\d\d", nums)]
    return ids + EXTRA.get(name.split("[")[0], [])


def pytest_run(name, mark, extra=()):
    """Run pytest with JUnit XML into docs/phase3/raw and return (tests, seconds, exit code)."""
    RAW.mkdir(parents=True, exist_ok=True)
    xml = RAW / f"{name}-junit.xml"
    t0 = now()
    proc = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider", "-m", mark,
                           f"--junitxml={xml}", *extra], cwd=ROOT, capture_output=True, text=True)
    seconds = (now() - t0).total_seconds()
    tests = []
    for tc in ET.parse(xml).getroot().iter("testcase"):
        outcome = "passed"
        if tc.find("failure") is not None or tc.find("error") is not None:
            outcome = "failed"
        elif tc.find("skipped") is not None:
            outcome = "skipped"
        tests.append({"file": tc.get("classname", "").replace(".", "/") + ".py", "name": tc.get("name"),
                      "outcome": outcome, "time": float(tc.get("time", 0))})
    return tests, seconds, proc.returncode


def counts(tests):
    return {k: sum(t["outcome"] == k for t in tests) for k in ("passed", "failed", "skipped")} | {"total": len(tests)}


def save(name, lines, data):
    OUT.mkdir(parents=True, exist_ok=True)
    RAW.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text("\n".join(lines) + "\n", encoding="utf-8")
    (RAW / (Path(name).stem.lower() + ".json")).write_text(json.dumps(data, indent=1), encoding="utf-8")
    print(f"wrote docs/phase3/{name}")


# ------------------------------------------------------------------ unit
def unit(_):
    tests, secs, _rc = pytest_run("unit", UNIT_MARK)
    c = counts(tests)
    L = header("Unit test report", "Results of the unit and component tests (STP section 4, level 1): every module of "
               "the Web Server and every model microservice tested in isolation, through its Python API or its HTTP "
               "contract with Flask's test client. Browser and performance tests are in the System Validation Report.",
               "unit")
    L += ["## 1. Summary", "", "| Tests | Passed | Failed | Skipped | Duration |", "|---|---|---|---|---|",
          f"| {c['total']} | {c['passed']} | {c['failed']} | {c['skipped']} | {secs:.0f} s |", ""]
    L += ["## 2. Results per test module", "", "| Test module | What it tests | Tests | Passed | Failed | Skipped |",
          "|---|---|---|---|---|---|"]
    mods = {}
    for t in tests:
        mods.setdefault(t["file"], []).append(t)
    for f, ts in sorted(mods.items()):
        mc = counts(ts)
        L.append(f"| `{f}` | {MODULE_DOC.get(Path(f).stem, '-')} | {mc['total']} | {mc['passed']} | {mc['failed']} | "
                 f"{mc['skipped']} |")
    L += ["", "## 3. Every test", "", "| # | Module | Test | STP case(s) | Result | Time |", "|---|---|---|---|---|---|"]
    for i, t in enumerate(tests, 1):
        ids = ", ".join(dict.fromkeys(tc_ids(t["name"]))) or "-"
        L.append(f"| {i} | {Path(t['file']).stem} | `{t['name']}` | {ids} | {t['outcome']} | {t['time']:.2f} s |")
    failed = [t for t in tests if t["outcome"] == "failed"]
    L += ["", "## 4. Defects", ""]
    L += [f"- `{t['file']}::{t['name']}` failed - see raw/unit-junit.xml" for t in failed] or ["None. All tests passed."]
    L += ["", "Raw evidence: `docs/phase3/raw/unit-junit.xml` (JUnit XML)."]
    save("UNIT_TEST_REPORT.md", L, {"counts": c, "seconds": secs})


