# ------------------------------------------------------------------ coverage
def run_coverage(name, branch):
    extra = [f"--cov={s}" for s in SOURCES] + ["--cov-report=", f"--cov-report=xml:{RAW / (name + '.xml')}",
                                               f"--cov-report=json:{RAW / (name + '-coverage.json')}"]
    if branch:
        extra.append("--cov-branch")
    tests, secs, _rc = pytest_run(name, UNIT_MARK, extra)
    return tests, secs, json.loads((RAW / (name + "-coverage.json")).read_text())


def ranges(lines):
    out, start, prev = [], None, None
    for n in sorted(lines):
        if start is None:
            start = prev = n
        elif n == prev + 1:
            prev = n
        else:
            out.append(f"{start}-{prev}" if start != prev else str(start))
            start = prev = n
    if start is not None:
        out.append(f"{start}-{prev}" if start != prev else str(start))
    return ", ".join(out)


def coverage(_):
    tests, secs, cov = run_coverage("coverage", branch=False)
    tot = cov["totals"]
    L = header("Code coverage report (statement coverage)", "How much of the production code (`server/`, `services/`, "
               "`shared/`) is executed by the unit and component tests. Measured with coverage.py through pytest-cov.",
               "coverage")
    L += ["## 1. Summary", "", "| Statements | Executed | Missed | Coverage | Tests run |", "|---|---|---|---|---|",
          f"| {tot['num_statements']} | {tot['covered_lines']} | {tot['missing_lines']} | "
          f"**{tot['percent_covered']:.1f} %** | {len(tests)} ({counts(tests)['failed']} failed) |", "",
          "Not measured: `training/` (offline scripts that build the model files; they are not part of the running "
          "system) and `client/` (JavaScript, covered by the browser tests in the System Validation Report).", ""]
    L += ["## 2. Coverage per file", "", "| File | Statements | Missed | Coverage | Lines not executed |",
          "|---|---|---|---|---|"]
    for f, d in sorted(cov["files"].items()):
        s = d["summary"]
        L.append(f"| `{f}` | {s['num_statements']} | {s['missing_lines']} | {s['percent_covered']:.1f} % | "
                 f"{ranges(d['missing_lines']) or '-'} |")
    L += ["", "## 3. Reading the gaps", "",
          "The lines not executed are mostly defensive branches for failures that the tests do not provoke "
          "(for example an operating-system error while writing a file) and the `__main__` start-up code of each "
          "process, which `run_all.py` runs but the in-process tests do not.", "",
          "Raw evidence: `docs/phase3/raw/coverage.xml` (Cobertura XML) and `raw/coverage-coverage.json`."]
    save("CODE_COVERAGE_REPORT.md", L, {"percent": tot["percent_covered"], "statements": tot["num_statements"],
                                        "missed": tot["missing_lines"], "tests": counts(tests), "seconds": secs})


def branch(_):
    tests, secs, cov = run_coverage("branch", branch=True)
    tot = cov["totals"]
    bpct = 100 * tot["covered_branches"] / tot["num_branches"] if tot["num_branches"] else 100.0
    L = header("Branch coverage report", "Which decision outcomes (both sides of every `if`, loop and `try`) in the "
               "production code (`server/`, `services/`, `shared/`) are taken by the unit and component tests. "
               "Measured with coverage.py in branch mode.", "branch")
    L += ["## 1. Summary", "", "| Branches | Taken | Not taken | Branch coverage | Partially covered decisions |",
          "|---|---|---|---|---|",
          f"| {tot['num_branches']} | {tot['covered_branches']} | {tot['missing_branches']} | **{bpct:.1f} %** | "
          f"{tot['num_partial_branches']} |", "",
          f"Combined statement + branch coverage: {tot['percent_covered']:.1f} %.", ""]
    L += ["## 2. Branch coverage per file", "", "| File | Branches | Not taken | Branch coverage | Partial |",
          "|---|---|---|---|---|"]
    gaps = []
    for f, d in sorted(cov["files"].items()):
        s = d["summary"]
        nb = s["num_branches"]
        pct = 100 * s["covered_branches"] / nb if nb else 100.0
        L.append(f"| `{f}` | {nb} | {s['missing_branches']} | {pct:.1f} % | {s['num_partial_branches']} |")
        for a, b in d.get("missing_branches", []):
            gaps.append((f, a, b))
    L += ["", "## 3. Branches not taken", "",
          "Each row is a decision on line *from* whose outcome that would jump to line *to* was never taken "
          "(a negative *to* means leaving the function).", "", "| File | From line | To line |", "|---|---|---|"]
    L += [f"| `{f}` | {a} | {b} |" for f, a, b in gaps] or ["| - | - | - |"]
    L += ["", "Raw evidence: `docs/phase3/raw/branch.xml` (Cobertura XML with branch data) and "
          "`raw/branch-coverage.json`."]
    save("BRANCH_COVERAGE_REPORT.md", L, {"branch_percent": bpct, "branches": tot["num_branches"],
                                          "not_taken": tot["missing_branches"], "tests": counts(tests),
                                          "seconds": secs})


# ------------------------------------------------------------------ system validation
LEVELS = [("unit", "API, integration and unit", UNIT_MARK), ("ui", "Browser (Playwright, Chromium)", "ui"),
          ("perf", "Performance", "perf")]


def load_cases():
    if CASES_FILE.exists():
        return json.loads(CASES_FILE.read_text(encoding="utf-8"))["cases"]
    return CASES_STP


def req_ids(text):
    return re.findall(r"\b(?:REQ-(?:FD|UI|API)-\d\d|SR-\d\d|NFR-(?:Q|S)?\d\d|BR-\d\d)\b", text or "")


def system(_):
    cases = load_cases()
    levels = []
    for key, label, mark in LEVELS:
        tests, secs, _rc = pytest_run(f"system-{key}", mark)
        levels.append((label, tests, secs))
    per_case = {k: [] for k in cases}
    for label, tests, _s in levels:
        for t in tests:
            for cid in tc_ids(t["name"]):
                if cid in per_case:
                    per_case[cid].append(t)

    manual_result = None
    usability = OUT / "USABILITY_WALKTHROUGH_RESULT.md"
    if usability.exists():
        m = re.search(r"Result:\s*\*\*(Pass|Fail)\*\*", usability.read_text(encoding="utf-8"))
        manual_result = m.group(1) if m else None

    def status(cid):
        ts = per_case[cid]
        if cid in MANUAL and not ts:
            return {"Pass": "Pass (manual)", "Fail": "FAIL (manual)"}.get(manual_result, "Not executed (manual)")
        if not ts:
            return "Not covered"
        if any(t["outcome"] == "failed" for t in ts):
            return "FAIL"
        return "Blocked" if all(t["outcome"] == "skipped" for t in ts) else "Pass"

    st = {c: status(c) for c in cases}
    reqs = {}
    for cid, v in cases.items():
        for r in req_ids(v.get("traceability", "")):
            reqs.setdefault(r, []).append(cid)
    passed = sum(s.startswith("Pass") for s in st.values())
    high = [c for c, v in cases.items() if v["priority"] == "High"]
    high_pass = sum(st[c].startswith("Pass") for c in high)
    all_tests = [t for _l, ts, _s in levels for t in ts]
    failed = [t for t in all_tests if t["outcome"] == "failed"]

    L = header("System validation report", "Validation of the whole system against the SRS (STP section 4, levels 2 "
               "and 3): integration of the Web Server with the three model microservices, end-to-end runs through "
               "the Web Client in a real browser, and the performance targets. Every SRS requirement is traced to "
               "the STP test cases that validate it.", "system")
    L += ["## 1. Test levels run", "", "| Level | Tests | Passed | Failed | Skipped | Duration |",
          "|---|---|---|---|---|---|"]
    for label, ts, secs in levels:
        c = counts(ts)
        L.append(f"| {label} | {c['total']} | {c['passed']} | {c['failed']} | {c['skipped']} | {secs:.0f} s |")
    c = counts(all_tests)
    L += [f"| **Total** | **{c['total']}** | **{c['passed']}** | **{c['failed']}** | **{c['skipped']}** | "
          f"**{sum(s for *_x, s in levels):.0f} s** |", ""]
    pct = 100 * passed / len(cases)
    L += ["## 2. Acceptance criteria (STP section 8)", "", "| Criterion | Result | Met |", "|---|---|---|",
          f"| All High-priority cases pass | {high_pass} of {len(high)} | {'Yes' if high_pass == len(high) else 'No'} |",
          f"| At least 90 % of the {len(cases)} cases pass | {passed} of {len(cases)} = {pct:.1f} % | "
          f"{'Yes' if pct >= 90 else 'No'} |",
          f"| No High-severity defect open | {'none' if not failed else str(len(failed)) + ' failing tests'} | "
          f"{'Yes' if not failed else 'No'} |", ""]
    ok = high_pass == len(high) and pct >= 90 and not failed
    L += [f"**Validation verdict: {'the system meets the SRS acceptance criteria.' if ok else 'NOT accepted yet.'}**",
          ""]
    L += ["## 3. Requirement validation matrix", "",
          "Each SRS requirement, the STP cases that validate it, and the result. A requirement is *Validated* when "
          "every case tracing to it passes.", "", "| Requirement | Validated by | Result |", "|---|---|---|"]
    order = {"REQ-FD": 0, "REQ-UI": 1, "REQ-API": 2, "SR": 3, "NFR": 4, "BR": 5}
    for r in sorted(reqs, key=lambda x: (order.get(x.rsplit("-", 1)[0].rstrip("QS") if x.startswith("NFR") else
                                                   x.rsplit("-", 1)[0], 9), x)):
        res = [st[c] for c in reqs[r]]
        verdict = ("Validated" if all(s.startswith("Pass") for s in res) else
                   "Not validated" if any("FAIL" in s for s in res) else "Partly validated")
        L.append(f"| {r} | {', '.join(reqs[r])} | {verdict} |")
    L += ["", "## 4. Results per STP test case", "", "| Case | Title | Priority | Result | Automated test(s) |",
          "|---|---|---|---|---|"]
    for cid, v in cases.items():
        names = sorted({f"`{Path(t['file']).stem}::{t['name'].split('[')[0]}`" for t in per_case[cid]})
        L.append(f"| {cid} | {v['title']} | {v['priority']} | {st[cid]} | {'<br>'.join(names) or '-'} |")
    L += ["", "TC-SAFE-04 is a manual usability walkthrough; its result is read from "
          "`docs/phase3/USABILITY_WALKTHROUGH_RESULT.md` when that file exists.", "",
          "Raw evidence: `docs/phase3/raw/system-unit-junit.xml`, `system-ui-junit.xml`, `system-perf-junit.xml`."]
    save("SYSTEM_VALIDATION_REPORT.md", L, {"cases": len(cases), "passed": passed, "high": len(high),
                                            "high_passed": high_pass, "tests": c, "verdict_ok": ok,
                                            "requirements": len(reqs),
                                            "validated": sum(all(st[x].startswith("Pass") for x in v)
                                                             for v in reqs.values())})


# ------------------------------------------------------------------ test case document
def cases_doc(_):
    data = json.loads(CASES_FILE.read_text(encoding="utf-8"))
    cases = data["cases"]
    collected = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q", "-p", "no:cacheprovider"],
                               cwd=ROOT, capture_output=True, text=True).stdout.splitlines()
    auto = {k: [] for k in cases}
    for line in collected:
        if "::" not in line:
            continue
        f, name = line.split("::", 1)
        for cid in tc_ids(name):
            if cid in auto:
                auto[cid].append(f"{Path(f).stem}::{name.split('[')[0]}")
    L = [f"# Test Case Document v{data['version']} (STP-CCFD test cases, updated after the sprints)", ""]
    L += data["intro"] + [""]
    L += ["## Change history", "", "| Version | Date | Change |", "|---|---|---|"]
    L += [f"| {h['version']} | {h['date']} | {h['change']} |" for h in data["history"]] + [""]
    L += ["## Summary of changes per case", "", "| Case | Change in this version |", "|---|---|"]
    L += [f"| {cid} | {v['change']} |" for cid, v in cases.items() if v.get("change")] + [""]
    L += ["## Test cases", ""]
    for cid, v in cases.items():
        L += [f"### {cid} - {v['title']}", "", "| Field | Value |", "|---|---|",
              f"| Priority / Type / Est. | {v['priority']} / {v['type']} / {v['est_min']} min |",
              f"| Objective | {v.get('objective', '-')} |", f"| Traceability | {v.get('traceability', '-')} |",
              f"| Preconditions | {v.get('preconditions', '-')} |"]
        if v.get("test_data"):
            L.append(f"| Test data | {v['test_data']} |")
        L += [f"| Steps | {v.get('steps', '-')} |", f"| Expected | {v.get('expected', '-')} |",
              f"| Pass criterion | {v.get('pass', '-')} |",
              f"| Execution | {'Manual' if cid in MANUAL else 'Automated'} |",
              f"| Automated test(s) | {'<br>'.join(f'`{x}`' for x in dict.fromkeys(auto[cid])) or '-'} |"]
        if v.get("change"):
            L.append(f"| **Changed in v{data['version']}** | {v['change']} |")
        L.append("")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "TEST_CASE_DOCUMENT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote docs/phase3/TEST_CASE_DOCUMENT.md")


# ------------------------------------------------------------------ summary
def summary(_):
    def raw(n):
        p = RAW / f"{n}.json"
        return json.loads(p.read_text()) if p.exists() else None
    u, cv, br, sv = raw("unit_test_report"), raw("code_coverage_report"), raw("branch_coverage_report"), \
        raw("system_validation_report")
    L = header("Test summary report (Phase 3)", "One page that collects the results of the Phase 3 test reports "
               "(STP section 10, deliverable 5).", "summary")
    L += ["## Reports", "", "| Report | Headline result | Owner |", "|---|---|---|"]
    L.append("| [Test Case Document](TEST_CASE_DOCUMENT.md) | STP cases updated after Sprints 1-2 (57 updated, 2 new) | Aman Priyansh |")
    u_text = f"{u['counts']['passed']} of {u['counts']['total']} tests passed" if u else "not generated yet"
    cv_text = f"{cv['percent']:.1f} % of statements" if cv else "not generated yet"
    br_text = f"{br['branch_percent']:.1f} % of branches" if br else "not generated yet"
    L.append(f"| [Unit Test Report](UNIT_TEST_REPORT.md) | {u_text} | Akshat Agarwal |")
    L.append(f"| [Code Coverage Report](CODE_COVERAGE_REPORT.md) | {cv_text} | Akshat Agarwal |")
    L.append(f"| [Branch Coverage Report](BRANCH_COVERAGE_REPORT.md) | {br_text} | Aditya Kalloli |")
    sv_text = (f"{sv['passed']} of {sv['cases']} STP cases pass; {sv['validated']} of {sv['requirements']} "
               f"requirements validated" if sv else "not generated yet")
    L.append(f"| [System Validation Report](SYSTEM_VALIDATION_REPORT.md) | {sv_text} | Aditya Kalloli |")
    L.append("| [Usability walkthrough result](USABILITY_WALKTHROUGH_RESULT.md) | TC-SAFE-04 (manual) | "
             "Aman Priyansh |")
    L += ["", "## Verdict", ""]
    if sv:
        L.append("Release 1.0 meets the STP acceptance criteria." if sv["verdict_ok"] else
                 "Release 1.0 does not meet the STP acceptance criteria yet - see the System Validation Report.")
    else:
        L.append("Pending: the System Validation Report has not been generated yet.")
    save("TEST_SUMMARY_REPORT.md", L, {"unit": u, "coverage": cv, "branch": br, "system": sv})


def main():
    cmds = {"unit": unit, "coverage": coverage, "branch": branch, "system": system, "cases": cases_doc,
            "summary": summary}
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("report", choices=cmds)
    a = ap.parse_args()
    cmds[a.report](a)


if __name__ == "__main__":
    main()
